    private void togBBloqueoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_togBBloqueoActionPerformed
        // TODO add your handling code here:
        Color valorInicio = Color.YELLOW;
        Color valorFinal = Color.GREEN;

        if(togBBloqueo.isSelected()){
            togBBloqueo.setText("Bloqueado");
            togBBloqueo.setBackground(valorFinal);
            tbNombre.setEnabled(false);
            tbApellido.setEnabled(false);

        }else{
            togBBloqueo.setText("Desbloqueado");
            togBBloqueo.setBackground(valorInicio);
            tbNombre.setEnabled(true);
            tbApellido.setEnabled(true);
        }
    }//GEN-LAST:event_togBBloqueoActionPerformed

